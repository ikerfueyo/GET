import Link from 'next/link';
import { OFFERS, PRODUCTS, STORES } from '@get/shared';
import { Logo } from './logo';
import { ensureCatalog } from '../lib/catalog';

// read from Supabase on each request, never at build time
export const dynamic = 'force-dynamic';

export default async function Home() {
  await ensureCatalog();
  const cities = new Set(STORES.map((s) => s.city));
  const countries = new Set(STORES.map((s) => s.country));
  return (
    <>
      <div className="row" style={{ gap: 24, margin: '12px 0 8px' }}>
        <Logo size={88} />
        <div>
          <h1>GET</h1>
          <p className="sub">Anything, anywhere, in one click. This is the operator side of the simulated marketplace.</p>
        </div>
      </div>
      <div className="stats">
        <div className="stat"><b>{STORES.length}</b>stores</div>
        <div className="stat"><b>{PRODUCTS.length}</b>products &amp; services</div>
        <div className="stat"><b>{OFFERS.length}</b>offers</div>
        <div className="stat"><b>{cities.size}</b>cities in {countries.size} countries</div>
      </div>
      <p className="note">
        No business is connected yet: inventory, prices and stock are generated by <code>packages/shared/src/seed.ts</code> and
        seeded into Supabase with <code>supabase/seed.sql</code>. Payments are simulated.
      </p>
      <p>
        <Link href="/search?q=baseball+bat">Try a search →</Link>
      </p>
    </>
  );
}
